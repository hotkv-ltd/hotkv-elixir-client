defmodule HotKV.TLSTest do
  @moduledoc """
  TLS verification against a fake RESP server over `:ssl`, with certificates
  generated by the `openssl` command line tool (the tests are skipped
  without it).
  """
  use ExUnit.Case, async: true

  alias HotKV.TestSupport.FakeServer

  @moduletag :tls

  setup_all do
    if System.find_executable("openssl") do
      dir = Path.join(System.tmp_dir!(), "hotkv-tls-test-#{System.unique_integer([:positive])}")
      File.mkdir_p!(dir)
      on_exit(fn -> File.rm_rf(dir) end)
      {:ok, dir: dir}
    else
      {:ok, dir: nil}
    end
  end

  defp openssl!(args, dir) do
    {out, status} = System.cmd("openssl", args, cd: dir, stderr_to_stdout: true)
    if status != 0, do: flunk("openssl #{Enum.join(args, " ")} failed: #{out}")
  end

  # A self-signed certificate (also a CA) for 127.0.0.1 / localhost.
  defp self_signed(dir, name) do
    openssl!(
      ~w(req -x509 -newkey rsa:2048 -nodes -keyout #{name}.key -out #{name}.pem -subj /CN=#{name}
         -days 2 -addext subjectAltName=IP:127.0.0.1,DNS:localhost
         -addext basicConstraints=critical,CA:TRUE),
      dir
    )

    {Path.join(dir, name <> ".pem"), Path.join(dir, name <> ".key")}
  end

  # A CA, and a leaf for 127.0.0.1 signed by it.
  defp ca_and_leaf(dir, name) do
    ca = name <> "-ca"

    openssl!(
      ~w(req -x509 -newkey rsa:2048 -nodes -keyout #{ca}.key -out #{ca}.pem -subj /CN=#{ca} -days 2
                -addext basicConstraints=critical,CA:TRUE -addext keyUsage=keyCertSign),
      dir
    )

    openssl!(
      ~w(req -newkey rsa:2048 -nodes -keyout #{name}.key -out #{name}.csr -subj /CN=#{name}),
      dir
    )

    File.write!(Path.join(dir, name <> ".ext"), "subjectAltName=IP:127.0.0.1,DNS:localhost\n")

    openssl!(
      ~w(x509 -req -in #{name}.csr -CA #{ca}.pem -CAkey #{ca}.key -CAcreateserial -out #{name}.pem
                -days 2 -extfile #{name}.ext),
      dir
    )

    {Path.join(dir, ca <> ".pem"), Path.join(dir, name <> ".pem"), Path.join(dir, name <> ".key")}
  end

  defp serve(certfile, keyfile) do
    FakeServer.start(
      fn
        ["HELLO" | _] -> FakeServer.error("ERR unknown command 'HELLO'")
        ["PING"] -> FakeServer.simple("PONG")
        _ -> nil
      end,
      tls: [certfile: String.to_charlist(certfile), keyfile: String.to_charlist(keyfile)]
    )
  end

  defp connect(port, tls_opts) do
    parent = self()

    # The connection is linked to its starter, so start it from a process that
    # outlives this call (it is linked to the test and ends with it).
    spawn_link(fn ->
      send(
        parent,
        {:connect,
         HotKV.start_link(
           host: "127.0.0.1",
           port: port,
           tls: true,
           tls_opts: tls_opts,
           connect_timeout: 3_000
         )}
      )

      Process.sleep(:infinity)
    end)

    receive do
      {:connect, result} -> result
    after
      6_000 -> flunk("connect did not return")
    end
  end

  test "a self-signed server certificate is trusted when it is the :ca_file", %{dir: dir} do
    if dir do
      {cert, key} = self_signed(dir, "selfsigned")
      {port, _} = serve(cert, key)

      assert {:ok, conn} = connect(port, ca_file: cert)
      assert {:ok, "PONG"} = HotKV.command(conn, ["PING"])
    end
  end

  test "a self-signed certificate that is not in the :ca_file is rejected", %{dir: dir} do
    if dir do
      {cert, key} = self_signed(dir, "server-a")
      {other_cert, _} = self_signed(dir, "server-b")
      {port, _} = serve(cert, key)

      assert {:error, %HotKV.Error{kind: :connection}} = connect(port, ca_file: other_cert)
    end
  end

  test "a certificate signed by the :ca_file CA is trusted", %{dir: dir} do
    if dir do
      {ca, cert, key} = ca_and_leaf(dir, "leaf")
      {port, _} = serve(cert, key)

      assert {:ok, conn} = connect(port, ca_file: ca)
      assert {:ok, "PONG"} = HotKV.command(conn, ["PING"])
    end
  end

  test "the hostname is still checked for a trusted certificate", %{dir: dir} do
    if dir do
      {cert, key} = self_signed(dir, "hostcheck")
      {port, _} = serve(cert, key)

      # the right name works, a name the certificate does not carry does not
      assert {:ok, _} = connect(port, ca_file: cert, server_name: "localhost")

      assert {:error, %HotKV.Error{kind: :connection}} =
               connect(port, ca_file: cert, server_name: "not-this-host.example")
    end
  end

  test "the hostname is checked for a CA-signed certificate too", %{dir: dir} do
    if dir do
      {ca, cert, key} = ca_and_leaf(dir, "leaf2")
      {port, _} = serve(cert, key)

      assert {:ok, _} = connect(port, ca_file: ca, server_name: "localhost")

      assert {:error, %HotKV.Error{kind: :connection}} =
               connect(port, ca_file: ca, server_name: "not-this-host.example")
    end
  end

  test "insecure_skip_verify accepts any certificate", %{dir: dir} do
    if dir do
      {cert, key} = self_signed(dir, "insecure")
      {port, _} = serve(cert, key)

      assert {:error, _} = connect(port, [])
      assert {:ok, conn} = connect(port, insecure_skip_verify: true)
      assert {:ok, "PONG"} = HotKV.command(conn, ["PING"])
    end
  end
end
